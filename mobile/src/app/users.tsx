import { useState } from "react";
import { Text, View } from "react-native";
import { useSession } from "../lib/session";
import { useAppearance } from "../lib/appearance";
import { userApi } from "../api/services";
import { Badge, Btn, Card, Chip, Empty, Field, QueryState, Screen, Title, friendlyMessage, useAsync, useDebounced } from "../ui/kit";
import { pretty, roleLabel } from "../lib/format";
import type { Role } from "../lib/types";

const CREATE_ROLES: Role[] = ["TEACHER", "ACCOUNT_OFFICER", "PRINCIPAL", "SCHOOL_ADMIN", "PARENT"];

export default function Users() {
  const { user } = useSession();
  const { colors } = useAppearance();
  const [q, setQ] = useState("");
  const dq = useDebounced(q, 350);
  const [role, setRole] = useState<Role | "">("");
  const list = useAsync(() => userApi.list({ q: dq || undefined, role: role || undefined }), [dq, role]);
  const [firstName, setFirst] = useState("");
  const [lastName, setLast] = useState("");
  const [email, setEmail] = useState("");
  const [phone, setPhone] = useState("");
  const [newRole, setNewRole] = useState<Role>("TEACHER");
  const [temp, setTemp] = useState("");
  const [err, setErr] = useState("");
  if (!user || !["SCHOOL_ADMIN", "PRINCIPAL"].includes(user.role)) {
    return <Screen colors={colors}><Empty title="Not permitted" colors={colors} /></Screen>;
  }
  const admin = user.role === "SCHOOL_ADMIN";
  return (
    <Screen colors={colors} onRefresh={() => void list.reload()} refreshing={list.loading}>
      <Title title="Users" subtitle="Staff and family accounts. Phone is kept. Usernames are generated by the server." colors={colors} />
      {admin ? (
        <Card colors={colors}>
          <Text style={{ color: colors.ink, fontWeight: "800", marginBottom: 8 }}>Create user</Text>
          <Field label="First name" colors={colors} value={firstName} onChangeText={setFirst} />
          <Field label="Last name" colors={colors} value={lastName} onChangeText={setLast} />
          <Field label="Email (optional)" colors={colors} value={email} onChangeText={setEmail} autoCapitalize="none" />
          <Field label="Phone (optional)" colors={colors} value={phone} onChangeText={setPhone} />
          <View style={{ flexDirection: "row", flexWrap: "wrap", gap: 8, marginBottom: 10 }}>
            {CREATE_ROLES.map((r) => (
              <Chip key={r} label={roleLabel(r)} selected={newRole === r} onPress={() => setNewRole(r)} colors={colors} />
            ))}
          </View>
          {err ? <Text style={{ color: colors.bad, marginBottom: 8 }}>{err}</Text> : null}
          {temp ? <Text style={{ color: colors.ok, marginBottom: 8 }}>{temp}</Text> : null}
          <Btn
            label="Create"
            colors={colors}
            disabled={!firstName.trim() || !lastName.trim()}
            onPress={async () => {
              setErr("");
              setTemp("");
              try {
                const created = await userApi.create({
                  firstName: firstName.trim(),
                  lastName: lastName.trim(),
                  email: email.trim() || undefined,
                  phone: phone.trim() || undefined,
                  role: newRole,
                });
                setTemp(
                  created.temporaryPassword
                    ? `Created ${created.user?.username || ""}. Temporary password: ${created.temporaryPassword}`
                    : created.message || "User created.",
                );
                setFirst("");
                setLast("");
                setEmail("");
                setPhone("");
                await list.reload();
              } catch (e) {
                setErr(friendlyMessage(e));
              }
            }}
          />
        </Card>
      ) : null}
      <Field label="Search" colors={colors} value={q} onChangeText={setQ} />
      <View style={{ flexDirection: "row", flexWrap: "wrap", gap: 8, marginBottom: 12 }}>
        <Chip label="All" selected={!role} onPress={() => setRole("")} colors={colors} />
        {CREATE_ROLES.concat(["STUDENT"]).map((r) => (
          <Chip key={r} label={roleLabel(r)} selected={role === r} onPress={() => setRole(r)} colors={colors} />
        ))}
      </View>
      <QueryState loading={list.loading} error={list.error} data={list.data?.content} onRetry={() => void list.reload()} colors={colors} empty={<Empty title="No users" hint="Try another search or role filter." colors={colors} />}>
        {(list.data?.content || []).map((u) => (
          <Card key={u.id} colors={colors}>
            <Text style={{ color: colors.ink, fontWeight: "800" }}>{u.fullName || u.username}</Text>
            <Text style={{ color: colors.muted }}>{roleLabel(u.role as Role)} · {u.phone || "no phone"} · {u.username}</Text>
            <Badge value={u.status} colors={colors} />
            {admin ? (
              <View style={{ gap: 8, marginTop: 8 }}>
                <Btn
                  label={u.status === "ACTIVE" ? "Deactivate" : "Activate"}
                  kind="ghost"
                  colors={colors}
                  onPress={async () => {
                    if (u.status === "ACTIVE") await userApi.deactivate(u.id);
                    else await userApi.activate(u.id);
                    await list.reload();
                  }}
                />
                <Btn
                  label="Reset password"
                  kind="ghost"
                  colors={colors}
                  onPress={async () => {
                    const r = await userApi.resetPassword(u.id);
                    setTemp(r.temporaryPassword ? `New password for ${u.username}: ${r.temporaryPassword}` : r.message || "Password reset.");
                  }}
                />
              </View>
            ) : null}
          </Card>
        ))}
      </QueryState>
      <Text style={{ color: colors.muted, fontSize: 12 }}>Bulk class inactivate stays on the web console. Status {pretty(list.data ? String(list.data.totalElements) : "")} users.</Text>
    </Screen>
  );
}
